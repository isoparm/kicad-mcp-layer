BOARD_X0, BOARD_Y0, BOARD_W, BOARD_H, BOARD_R = 50.0, 50.0, 170.0, 52.0, 3.0
CELL = 4.0
TEXT_X0, TEXT_Y0 = 74.0, 59.0     # centre of cell (0,0) of letter 0
LETTER_ADVANCE = 14.0
FET_Y = 82.0
MCU_X, MCU_Y = 144.0, 90.0
TRACK = 0.2
TRACK_POWER = 0.3


def letter_x0(L: Letter) -> float:
    return TEXT_X0 + LETTER_ADVANCE * L.index + (WORD_GAP_AFTER if L.index >= 5 else 0.0)


def cell_center(L: Letter, cell: tuple[int, int]) -> tuple[float, float]:
    c, r = cell
    return (letter_x0(L) + CELL * c, TEXT_Y0 + CELL * r)


def node_of(L: Letter, cell: tuple[int, int]) -> tuple[float, float]:
    """Bottom-right corner node of a cell: where the letter net rails meet."""
    cx, cy = cell_center(L, cell)
    return (cx + CELL / 2, cy + CELL / 2)


STRAIGHT = [(0, -1), (0, 1), (-1, 0), (1, 0)]
DIAGONAL = [(-1, -1), (1, -1), (-1, 1), (1, 1)]

NodeIx = tuple[int, int]   # rail node index: the bottom-right corner of cell (c, r) is node (c + 1, r + 1)


def _unit_segments(path: list[NodeIx]) -> list[tuple[NodeIx, NodeIx]]:
    segs = []
    for a, b in zip(path, path[1:]):
        if a[0] == b[0]:
            step = 1 if b[1] > a[1] else -1
            for j in range(a[1], b[1], step):
                lo, hi = sorted((j, j + step))
                segs.append(((a[0], lo), (a[0], hi)))
        else:
            step = 1 if b[0] > a[0] else -1
            for i in range(a[0], b[0], step):
                lo, hi = sorted((i, i + step))
                segs.append(((lo, a[1]), (hi, a[1])))
    return segs


def _seal_score(path: list[NodeIx], cellset: set[tuple[int, int]]) -> int:
    """How much a rail path seals LED cells off from the +5V pour.

    A rail on a cell's top edge blocks the pour that feeds its anode (3). A rail on a side
    edge narrows the way in (1). A rail on a bottom edge is harmless (0).
    """
    score = 0
    for (i, j), (i2, j2) in _unit_segments(path):
        if j == j2:                      # horizontal unit segment between node columns i..i2 at row j
            if (i, j) in cellset:        # top edge of cell (i, j)
                score += 3
        else:                            # vertical unit segment at node column i between rows j..j2
            if (i - 1, j) in cellset:    # right edge of cell (i-1, j)
                score += 1
            if (i, j) in cellset:        # left edge of cell (i, j)
                score += 1
    return score


def _best_path(na: NodeIx, nb: NodeIx, cellset: set[tuple[int, int]]) -> tuple[int, list[NodeIx]]:
    if na[0] == nb[0] or na[1] == nb[1]:
        p = [na, nb]
        return _seal_score(p, cellset), p
    a = [na, (nb[0], na[1]), nb]   # horizontal first
    b = [na, (na[0], nb[1]), nb]   # vertical first
    sa, sb = _seal_score(a, cellset), _seal_score(b, cellset)
    if sa == sb:
        # tie: put the horizontal leg at the lower row
        return (sa, a) if na[1] >= nb[1] else (sb, b)
    return (sa, a) if sa < sb else (sb, b)


def node_ix(cell: tuple[int, int]) -> NodeIx:
    return (cell[0] + 1, cell[1] + 1)


def letter_rails(cells: list[tuple[int, int]], root: tuple[int, int]) -> list[list[NodeIx]]:
    """Rail paths (in node indices) that join every cell of a letter into one net.

    Straight neighbours are joined first. When a letter falls apart into pieces (the ring
    of an O, the bowls of R and D), the diagonal link with the lowest seal score is added,
    with the better of its two detours.
    """
    cellset = set(cells)
    seen = {root}
    order = [root]
    paths: list[list[NodeIx]] = []
    frontier = [root]
    while True:
        q = deque(frontier)
        while q:
            cur = q.popleft()
            for dc, dr in STRAIGHT:
                nb = (cur[0] + dc, cur[1] + dr)
                if nb in cellset and nb not in seen:
                    seen.add(nb)
                    order.append(nb)
                    paths.append([node_ix(cur), node_ix(nb)])
                    q.append(nb)
        if seen == cellset:
            return paths
        best = None
        for cur in order:
            for dc, dr in DIAGONAL:
                nb = (cur[0] + dc, cur[1] + dr)
                if nb in cellset and nb not in seen:
                    score, path = _best_path(node_ix(cur), node_ix(nb), cellset)
                    if best is None or score < best[0]:
                        best = (score, path, nb)
        assert best, f"letter cells not connected: {cellset - seen}"
        _, path, nb = best
        seen.add(nb)
        order.append(nb)
        paths.append(path)
        frontier = [nb]


def bottom_root(L: Letter) -> tuple[int, int]:
    bottom = [c for c in L.cells if c[1] == 4]
    return min(bottom, key=lambda c: (abs(c[0] - 1), c[0]))


def build_board(out_path: Path, sheetfile: str, ls: list[Letter], netlist: Netlist, sym_uuid: dict[str, str], setup_template: Path | None) -> dict:
    pcb = BoardBuilder(sheetfile=sheetfile, title="HELLO WORLD LED display", date="2026-09-04", rev="v0.1", company="kicad-mcp-layer", setup_template=setup_template)
    pad_net: dict[tuple[str, str], str] = {}
    for net in netlist.nets:
        for node in net.nodes:
            pad_net[(node.ref, node.pin)] = net.name
    comps = {c.ref: c for c in netlist.components}

    def nets_for(ref: str) -> dict[str, str]:
        return {pin: name for (r, pin), name in pad_net.items() if r == ref}

    def place(ref: str, fp: tuple[str, str], at, rot=0.0, *, value_text="", hide_ref=False):
        footprint = load_footprint(*fp)
        comp = comps[ref]
        assert (comp.footprint or fp_id(fp)) == fp_id(fp), (ref, comp.footprint, fp_id(fp))
        # Fields come from the schematic so DRC's parity check sees identical text.
        node = pcb.footprint(
            footprint, ref, comp.value or value_text, at, rot,
            path_uuid=sym_uuid[ref], pad_nets=nets_for(ref), hide_ref=hide_ref,
            description=comp.fields.get("Description", ""), datasheet=comp.fields.get("Datasheet", ""),
        )
        return footprint, node

    x0, y0, x1, y1 = BOARD_X0, BOARD_Y0, BOARD_X0 + BOARD_W, BOARD_Y0 + BOARD_H
    pcb.rounded_rect_outline(x0, y0, x1, y1, BOARD_R)
    inset = 0.5
    pour = [(x0 + inset, y0 + inset), (x1 - inset, y0 + inset), (x1 - inset, y1 - inset), (x0 + inset, y1 - inset)]
    pcb.zone(net="+5V", layer="F.Cu", polygon=pour, name="+5V pour")
    pcb.zone(net="GND", layer="B.Cu", polygon=pour, name="GND pour")

    stats = {"tracks": 0, "vias": 0}

    def track(pts, net, width=TRACK, layer="F.Cu"):
        pcb.track(pts, width=width, layer=layer, net=net)
        stats["tracks"] += len(pts) - 1

    def via(p, net):
        pcb.via(p, net=net)
        stats["vias"] += 1

    # ---- LED matrix ------------------------------------------------------------------
    for L in ls:
        letter_net = f"LED_{L.net_suffix}"
        for cell in L.cells:
            cx, cy = cell_center(L, cell)
            dref, rref = L.led_refs[cell]
            led_fp, _ = place(dref, FP_LED, (cx - 0.9, cy), 90, value_text=LED_VALUE, hide_ref=True)
            r_fp, _ = place(rref, FP_R, (cx + 0.9, cy), 90, value_text=R_LED_VALUE, hide_ref=True)
            k = led_fp.pad_position("1", cx - 0.9, cy, 90)      # cathode, bottom
            r1 = r_fp.pad_position("1", cx + 0.9, cy, 90)       # bottom
            r2 = r_fp.pad_position("2", cx + 0.9, cy, 90)       # top -> letter net
            assert k[1] > cy and r2[1] < cy, (k, r2)
            junction_net = pad_net[(dref, "1")]
            track([k, (r1[0], k[1])], junction_net)
            rail_x = cx + CELL / 2
            track([r2, (rail_x, r2[1]), (rail_x, cy + CELL / 2)], letter_net)
            via((rail_x, cy + CELL / 2), letter_net)   # the letter rails run on the bottom layer
        root = bottom_root(L)
        def node_xy(n: NodeIx) -> tuple[float, float]:
            return (letter_x0(L) + CELL * n[0] - CELL / 2, TEXT_Y0 + CELL * n[1] - CELL / 2)

        for path in letter_rails(L.cells, root):
            track([node_xy(n) for n in path], letter_net, layer="B.Cu")
        # drop to the FET drain
        nx, ny = node_of(L, root)
        fx, fy = nx + 0.9375, FET_Y
        qref = f"Q{L.index + 1}"
        sot, _ = place(qref, FP_SOT23, (fx, fy), 180, value_text="2N7002")
        d = sot.pad_position("3", fx, fy, 180)
        g = sot.pad_position("1", fx, fy, 180)
        s = sot.pad_position("2", fx, fy, 180)
        assert abs(d[0] - nx) < 1e-6 and d[1] == fy, (d, nx)
        track([(nx, ny), d], letter_net)
        via_s = (s[0] + 1.3, s[1])
        track([s, via_s], "GND")
        via(via_s, "GND")
        # gate lane to the MCU
        soic = load_footprint(*FP_SOIC14)
        pin_pos = soic.pad_position(L.mcu_pin, MCU_X, MCU_Y, 0)
        gate_net = f"G_{L.net_suffix}"
        track([g, (g[0], pin_pos[1]), pin_pos], gate_net)
        pcb.text(L.char, (fx + 3.6, fy), size=1.2, thickness=0.2, bold=True)

    # ---- MCU, decoupling, header -----------------------------------------------------
    soic, _ = place("U1", FP_SOIC14, (MCU_X, MCU_Y), 0, value_text="ATtiny1614")
    gnd14 = soic.pad_position("14", MCU_X, MCU_Y, 0)
    via14 = (gnd14[0] + 1.6, gnd14[1])
    track([gnd14, via14], "GND")
    via(via14, "GND")
    updi_pad = soic.pad_position("10", MCU_X, MCU_Y, 0)

    hx, hy = MCU_X, 97.0
    hdr, _ = place("J2", FP_HDR3, (hx - 2.54, hy), 90, value_text="UPDI")
    h1 = hdr.pad_position("1", hx - 2.54, hy, 90)
    h2 = hdr.pad_position("2", hx - 2.54, hy, 90)
    h3 = hdr.pad_position("3", hx - 2.54, hy, 90)
    assert abs(h2[0] - hx) < 1e-6 and abs(h1[1] - hy) < 1e-6, (h1, h2, h3)
    track([h2, (hx, updi_pad[1]), updi_pad], "UPDI")
    via_h3 = (h3[0] + 2.0, h3[1])
    track([h3, via_h3], "GND")
    via(via_h3, "GND")
    pcb.text("UPDI", (hx, hy + 3.8), size=1.0, thickness=0.15)
    pcb.text("5V", (h1[0], hy + 2.3), size=1.0, thickness=0.15)
    pcb.text("GND", (h3[0], hy + 2.3), size=1.0, thickness=0.15)

    c2x, c2y = MCU_X - 9.0, 96.5
    c2, _ = place("C2", FP_C0603, (c2x, c2y), 0, value_text=C_DECOUPLE_VALUE, hide_ref=True)
    c2b = c2.pad_position("2", c2x, c2y, 0)
    via_c2 = (c2b[0] + 1.4, c2b[1])
    track([c2b, via_c2], "GND")
    via(via_c2, "GND")

    # ---- USB-C power entry (left edge, plug facing left) ------------------------------
    ox, oy = 54.15, 86.0
    usb, _ = place("J1", FP_USBC, (ox, oy), 270, value_text="USB-C")
    vbus_lo = usb.pad_position("A4", ox, oy, 270)
    vbus_hi = usb.pad_position("A9", ox, oy, 270)
    gnd_lo = usb.pad_position("A1", ox, oy, 270)
    gnd_hi = usb.pad_position("B1", ox, oy, 270)
    cc1 = usb.pad_position("A5", ox, oy, 270)
    cc2 = usb.pad_position("B5", ox, oy, 270)
    pad_x = vbus_lo[0]
    for vpad in (vbus_lo, vbus_hi):
        away = 1 if vpad[1] > oy else -1          # leave the connector towards the open pour
        track([vpad, (pad_x + 2.3, vpad[1]), (pad_x + 2.3, vpad[1] + 3.6 * away)], "+5V", width=TRACK_POWER)
    for gpad in (gnd_lo, gnd_hi):
        direction = 1 if gpad[1] > oy else -1
        v = (gpad[0], gpad[1] + 1.05 * direction)
        track([gpad, v], "GND", width=TRACK_POWER)
        via(v, "GND")
    # CC pull-downs
    rx = 62.6
    for (ccpad, rref) in ((cc1, "R90"), (cc2, "R91")):
        r, _ = place(rref, FP_R, (rx, ccpad[1]), 0, value_text=R_CC_VALUE, hide_ref=True)
        p1 = r.pad_position("1", rx, ccpad[1], 0)
        p2 = r.pad_position("2", rx, ccpad[1], 0)
        track([ccpad, p1], pad_net[(rref, "1")])
        v = (p2[0] + 1.2, p2[1])
        track([p2, v], "GND")
        via(v, "GND")
    # bulk capacitor
    c1x, c1y = 62.6, oy + 4.6
    c1, _ = place("C1", FP_C0805, (c1x, c1y), 0, value_text=C_BULK_VALUE, hide_ref=True)
    c1b = c1.pad_position("2", c1x, c1y, 0)
    v = (c1b[0] + 1.5, c1b[1])
    track([c1b, v], "GND")
    via(v, "GND")
    pcb.text("USB-C 5V", (61.5, 79.5), size=1.0, thickness=0.15)

    # ---- mounting holes ---------------------------------------------------------------
    for i, (hx_, hy_) in enumerate([(54.5, 54.0), (215.5, 54.0), (215.5, 98.0), (54.5, 98.0)]):
        place(f"H{i + 1}", FP_HOLE, (hx_, hy_), 0, value_text="M3", hide_ref=True)

    # ---- silkscreen -------------------------------------------------------------------
    pcb.text(f"HELLO WORLD  -  {LED_COUNT} LEDs  -  designed by kicad-mcp-layer", (135.0, 54.0), size=1.6, thickness=0.25, bold=True)
    pcb.text("v0.1  2026-09", (208.0, 99.5), size=1.0, thickness=0.15)

    pcb.write(str(out_path))
    return stats
