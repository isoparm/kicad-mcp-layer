"""The Hello World LED board: schematic and board layout.

Ten letters on a 3 by 5 LED grid each, one MOSFET channel per letter, an ATtiny1614
driving the channels, USB-C power, a UPDI header, four mounting holes. Every LED has its
own series resistor. Power is a +5V pour on the top layer and a ground pour on the bottom.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field
from pathlib import Path

from kicad_layer.kicad_libs import load_footprint
from kicad_layer.models import Netlist
from kicad_layer.pcb_writer import BoardBuilder
from kicad_layer.sch_writer import SchematicBuilder

# --------------------------------------------------------------------------------------
# the word
# --------------------------------------------------------------------------------------

# 3 columns x 5 rows, "#" = LED
FONT = {
    "H": ["#.#", "#.#", "###", "#.#", "#.#"],
    "E": ["###", "#..", "##.", "#..", "###"],
    "L": ["#..", "#..", "#..", "#..", "###"],
    "O": [".#.", "#.#", "#.#", "#.#", ".#."],
    "W": ["#.#", "#.#", "#.#", "###", "#.#"],
    "R": ["##.", "#.#", "##.", "#.#", "#.#"],
    "D": ["##.", "#.#", "#.#", "#.#", "##."],
}
WORD = "HELLOWORLD"
WORD_GAP_AFTER = 4  # extra gap after the 5th letter (index 4)


@dataclass
class Letter:
    index: int
    char: str
    net_suffix: str          # LED_H, LED_L1 ...
    cells: list[tuple[int, int]] = field(default_factory=list)   # (col, row)
    led_refs: dict[tuple[int, int], tuple[str, str]] = field(default_factory=dict)  # cell -> (D ref, R ref)
    mcu_pin: str = ""
    side: str = ""           # "left" or "right" of the MCU


def letters() -> list[Letter]:
    out: list[Letter] = []
    seen: dict[str, int] = {}
    for i, ch in enumerate(WORD):
        seen[ch] = seen.get(ch, 0) + 1
        suffix = ch if WORD.count(ch) == 1 else f"{ch}{seen[ch]}"
        cells = [(c, r) for r, row in enumerate(FONT[ch]) for c, v in enumerate(row) if v == "#"]
        out.append(Letter(index=i, char=ch, net_suffix=suffix, cells=cells))
    # MCU pin assignment: the letter nearest the MCU gets the topmost pin on its side.
    left_pins = ["2", "3", "4", "5", "6"]        # PA4 PA5 PA6 PA7 PB3, nearest first
    right_pins = ["13", "12", "11", "9", "8"]    # PA3 PA2 PA1 PB0 PB1, nearest first
    for k, pin in enumerate(left_pins):
        out[4 - k].mcu_pin, out[4 - k].side = pin, "left"
    for k, pin in enumerate(right_pins):
        out[5 + k].mcu_pin, out[5 + k].side = pin, "right"
    return out


def assign_refs(ls: list[Letter]) -> None:
    n = 0
    for L in ls:
        for cell in L.cells:
            n += 1
            L.led_refs[cell] = (f"D{n}", f"R{n}")


LED_COUNT = sum(len(L.cells) for L in letters())

