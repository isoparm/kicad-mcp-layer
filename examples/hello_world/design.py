FP_LED = ("LED_SMD", "LED_0603_1608Metric")
FP_R = ("Resistor_SMD", "R_0603_1608Metric")
FP_C0603 = ("Capacitor_SMD", "C_0603_1608Metric")
FP_C0805 = ("Capacitor_SMD", "C_0805_2012Metric")
FP_SOT23 = ("Package_TO_SOT_SMD", "SOT-23")
FP_SOIC14 = ("Package_SO", "SOIC-14_3.9x8.7mm_P1.27mm")
FP_USBC = ("Connector_USB", "USB_C_Receptacle_HRO_TYPE-C-31-M-12")
FP_HDR3 = ("Connector_PinHeader_2.54mm", "PinHeader_1x03_P2.54mm_Vertical")
FP_HOLE = ("MountingHole", "MountingHole_3.2mm_M3")

LED_VALUE = "LED red"
R_LED_VALUE = "1k"
R_CC_VALUE = "5.1k"
C_BULK_VALUE = "10uF"
C_DECOUPLE_VALUE = "100nF"

MCU_GPIO_NAME = {
    "2": "PA4", "3": "PA5", "4": "PA6", "5": "PA7", "6": "PB3", "7": "PB2",
    "8": "PB1", "9": "PB0", "10": "UPDI", "11": "PA1", "12": "PA2", "13": "PA3",
}


def fp_id(fp: tuple[str, str]) -> str:
    return f"{fp[0]}:{fp[1]}"


def _close(a: tuple[float, float], b: tuple[float, float], tol: float = 1e-3) -> bool:
    return abs(a[0] - b[0]) < tol and abs(a[1] - b[1]) < tol


