def build_schematic(out_path: Path, project_name: str, ls: list[Letter]) -> dict[str, str]:
    """Write the schematic; return {reference: symbol uuid} for the board's path links."""
    sch = SchematicBuilder(
        project_name,
        paper="A3",
        title="HELLO WORLD LED display",
        date="2026-09-04",
        rev="v0.1",
        company="kicad-mcp-layer",
        comments=[f"{LED_COUNT} LEDs, one MOSFET channel per letter, ATtiny1614 controller", "Generated by kicad-mcp-layer"],
    )
    uuids: dict[str, str] = {}

    def keep(p):
        uuids[p.ref] = p.uuid
        return p

    # ---- USB-C power entry (top left) -------------------------------------------
    ux, uy = 45.72, 63.5
    usb = keep(sch.place("Connector", "USB_C_Receptacle_USB2.0_16P", "J1", (ux, uy), footprint=fp_id(FP_USBC), value_text="USB-C 16P", ref_pos=(ux, uy - 27.94), value_pos=(ux, uy + 30.48)))
    vbus = usb.pin("A4")
    cc1 = usb.pin("A5")
    cc2 = usb.pin("B5")
    gnd_pin = usb.pin("A1")
    shield = usb.pin("SH")
    # VBUS -> +5V with a PWR_FLAG on the way
    flag_pt = (vbus[0] + 5.08, vbus[1])
    top_pt = (vbus[0] + 10.16, vbus[1])
    sch.wire(vbus, flag_pt)
    sch.wire(flag_pt, top_pt)
    sch.junction(flag_pt)
    keep(sch.pwr_flag(flag_pt))
    keep(sch.power("+5V", top_pt))
    # CC pull-downs
    cc2_end = (cc2[0] + 5.08, cc2[1])
    sch.wire(cc2, cc2_end)
    r_cc2 = keep(sch.place("Device", "R", "R91", (cc2_end[0], cc2_end[1] + 3.81), value_text=R_CC_VALUE, footprint=fp_id(FP_R), ref_pos=(cc2_end[0] + 2.54, cc2_end[1] + 3.81), value_pos=(cc2_end[0] + 2.54, cc2_end[1] + 6.35)))
    keep(sch.power("GND", r_cc2.pin("2")))
    cc1_end = (cc1[0] + 12.7, cc1[1])
    sch.wire(cc1, cc1_end)
    r_cc1 = keep(sch.place("Device", "R", "R90", (cc1_end[0], cc1_end[1] + 3.81), value_text=R_CC_VALUE, footprint=fp_id(FP_R), ref_pos=(cc1_end[0] + 2.54, cc1_end[1] + 3.81), value_pos=(cc1_end[0] + 2.54, cc1_end[1] + 6.35)))
    keep(sch.power("GND", r_cc1.pin("2")))
    # GND + shield + PWR_FLAG
    g_flag = (gnd_pin[0], gnd_pin[1] + 2.54)
    g_end = (gnd_pin[0], gnd_pin[1] + 5.08)
    sch.wire(gnd_pin, g_flag)
    sch.wire(g_flag, g_end)
    sch.junction(g_flag)
    keep(sch.pwr_flag(g_flag))
    keep(sch.power("GND", g_end))
    sch.wire(shield, (shield[0], g_end[1]))
    sch.wire((shield[0], g_end[1]), g_end)
    sch.junction(g_end)
    # unused USB pins
    for num in ("A6", "A7", "B6", "B7", "A8", "B8"):
        sch.no_connect(usb.pin(num))
    # bulk capacitor
    c1x, c1y = top_pt[0] + 12.7, vbus[1] + 3.81
    c1 = keep(sch.place("Device", "C", "C1", (c1x, c1y), value_text=C_BULK_VALUE, footprint=fp_id(FP_C0805), ref_pos=(c1x + 2.54, c1y - 1.27), value_pos=(c1x + 2.54, c1y + 1.27)))
    keep(sch.power("+5V", c1.pin("1")))
    keep(sch.power("GND", c1.pin("2")))
    sch.text("USB-C power input. CC pull-downs advertise a 5 V sink.", (ux - 15.24, uy - 33.02), size=1.5)

    # ---- MCU (top middle) ---------------------------------------------------------
    mx, my = 152.4, 63.5
    mcu = keep(sch.place("MCU_Microchip_ATtiny", "ATtiny1614-SS", "U1", (mx, my), footprint=fp_id(FP_SOIC14), ref_pos=(mx - 12.7, my - 20.32), value_pos=(mx, my + 20.32)))
    vcc = mcu.pin("1")
    gnd = mcu.pin("14")
    vcc_top = (vcc[0], vcc[1] - 2.54)
    sch.wire(vcc, vcc_top)
    keep(sch.power("+5V", vcc_top))
    gnd_bot = (gnd[0], gnd[1] + 2.54)
    sch.wire(gnd, gnd_bot)
    keep(sch.power("GND", gnd_bot))
    c2x, c2y = mx - 25.4, my - 15.24
    c2 = keep(sch.place("Device", "C", "C2", (c2x, c2y), value_text=C_DECOUPLE_VALUE, footprint=fp_id(FP_C0603), ref_pos=(c2x + 2.54, c2y - 1.27), value_pos=(c2x + 2.54, c2y + 1.27)))
    keep(sch.power("+5V", c2.pin("1")))
    keep(sch.power("GND", c2.pin("2")))
    for L in ls:
        p = mcu.pin(L.mcu_pin)
        if L.side == "left":
            end = (p[0] - 2.54, p[1])
            sch.wire(p, end)
            sch.label(f"G_{L.net_suffix}", end, rot=180)
        else:
            end = (p[0] + 2.54, p[1])
            sch.wire(p, end)
            sch.label(f"G_{L.net_suffix}", end, rot=0)
    updi = mcu.pin("10")
    updi_end = (updi[0] + 2.54, updi[1])
    sch.wire(updi, updi_end)
    sch.label("UPDI", updi_end, rot=0)
    sch.no_connect(mcu.pin("7"))
    sch.text("ATtiny1614: one GPIO per letter, UPDI programming.", (mx - 22.86, my - 25.4), size=1.5)

    # ---- UPDI header ---------------------------------------------------------------
    hx, hy = mx + 45.72, my
    hdr = keep(sch.place("Connector_Generic", "Conn_01x03", "J2", (hx, hy), value_text="UPDI", footprint=fp_id(FP_HDR3), ref_pos=(hx + 2.54, hy - 5.08), value_pos=(hx + 2.54, hy + 5.08)))
    p1, p2, p3 = hdr.pin("1"), hdr.pin("2"), hdr.pin("3")
    corner1 = (p1[0] - 2.54, p1[1])
    top1 = (corner1[0], corner1[1] - 2.54)
    sch.wire(p1, corner1)
    sch.wire(corner1, top1)
    keep(sch.power("+5V", top1))
    l2 = (p2[0] - 2.54, p2[1])
    sch.wire(p2, l2)
    sch.label("UPDI", l2, rot=180)
    corner3 = (p3[0] - 2.54, p3[1])
    bot3 = (corner3[0], corner3[1] + 2.54)
    sch.wire(p3, corner3)
    sch.wire(corner3, bot3)
    keep(sch.power("GND", bot3))

    # ---- mounting holes -------------------------------------------------------------
    for i in range(4):
        hxh, hyh = 45.72 + 15.24 * i, 120.65
        keep(sch.place("Mechanical", "MountingHole", f"H{i + 1}", (hxh, hyh), footprint=fp_id(FP_HOLE), value_text="M3", ref_pos=(hxh, hyh - 3.81), value_pos=(hxh, hyh + 3.81)))
    sch.text("Mounting holes", (45.72 - 5.08, 120.65 - 6.35), size=1.5)

    # ---- letter drivers and LED blocks ----------------------------------------------
    block_pitch = 30.48
    bx0 = 30.48
    qy = 149.86
    by = 175.26
    for L in ls:
        bx = bx0 + block_pitch * L.index
        qx = bx + 7.62
        q = keep(sch.place("Transistor_FET", "2N7002", f"Q{L.index + 1}", (qx, qy), footprint=fp_id(FP_SOT23), ref_pos=(qx + 6.35, qy - 1.27), value_pos=(qx + 6.35, qy + 1.27)))
        g, s, d = q.pin("1"), q.pin("2"), q.pin("3")
        g_end = (g[0] - 2.54, g[1])
        sch.wire(g, g_end)
        sch.label(f"G_{L.net_suffix}", g_end, rot=180)
        d_end = (d[0], d[1] - 2.54)
        sch.wire(d, d_end)
        sch.label(f"LED_{L.net_suffix}", d_end, rot=90)
        s_end = (s[0], s[1] + 2.54)
        sch.wire(s, s_end)
        keep(sch.power("GND", s_end))

        sch.text(f"{L.char}  ({len(L.cells)} LEDs)", (bx, by - 6.35), size=2.0)
        rail_x = bx
        bus_x = bx + 15.24
        n = len(L.cells)
        rows = [by + 5.08 * i for i in range(n)]
        for i, cell in enumerate(L.cells):
            y = rows[i]
            dref, rref = L.led_refs[cell]
            led = keep(sch.place("Device", "LED", dref, (rail_x + 3.81, y), rot=180, value_text=LED_VALUE, footprint=fp_id(FP_LED), ref_pos=(rail_x + 3.81, y - 2.54), value_pos=(rail_x + 3.81, y + 2.54), hide_value=True, text_size=1.0))
            res = keep(sch.place("Device", "R", rref, (rail_x + 11.43, y), rot=90, value_text=R_LED_VALUE, footprint=fp_id(FP_R), ref_pos=(rail_x + 11.43, y - 2.54), value_pos=(rail_x + 11.43, y + 2.54), hide_value=True, text_size=1.0))
            assert _close(led.pin("2"), (rail_x, y)), led.pin("2")
            assert _close(led.pin("1"), res.pin("1")), (led.pin("1"), res.pin("1"))
            assert _close(res.pin("2"), (bus_x, y)), res.pin("2")
        # +5V rail
        rail_top = (rail_x, rows[0] - 2.54)
        keep(sch.power("+5V", rail_top))
        sch.wire(rail_top, (rail_x, rows[0]))
        for a, b in zip(rows, rows[1:]):
            sch.wire((rail_x, a), (rail_x, b))
        for y in rows[:-1]:
            sch.junction((rail_x, y))
        # letter bus
        for a, b in zip(rows, rows[1:]):
            sch.wire((bus_x, a), (bus_x, b))
        for y in rows[1:]:
            sch.junction((bus_x, y))
        bus_end = (bus_x, rows[-1] + 2.54)
        sch.wire((bus_x, rows[-1]), bus_end)
        sch.label(f"LED_{L.net_suffix}", bus_end, rot=270)

    sch.text("Each letter: LEDs in parallel from +5V through 1k, switched low-side by its MOSFET.", (bx0, qy - 12.7), size=1.5)
    sch.write(str(out_path))
    return uuids


