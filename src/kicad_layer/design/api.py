"""The design package's API sheet: the one file a sheet author reads instead of the source.

``python -m kicad_layer.design.api`` writes ``docs/design-api.md`` from docstrings, signatures,
dataclass fields with their trailing comments, and the catalogue. ``tests/test_design_api.py``
fails when the file is stale, so the sheet is always what the code does.

Why: measured over the first two boards, reading the library's own source to recall its API was
about half of everything the model absorbed. The sheet is a few thousand tokens once per session.
"""

